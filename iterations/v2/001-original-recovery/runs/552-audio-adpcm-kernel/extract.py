"""Generate the exact 0059ae00 12x12 synthesis block from the original listing.

The body is one fully unrolled loop iteration. This script resolves every
`fld [esp+..]`/`fmul [esi+..]` pair, checks the structure and slot/count rules
against the original bytes, and writes the C++ statement order verbatim so the
recovered source keeps the original x87 summation order.

The original scheduler hoists `add edi,0x30`/`dec eax` before the last two
outputs, so output addresses are resolved with the running `edi` shift.
"""
import json
import re
from pathlib import Path

RUN = Path(__file__).resolve().parent
d = json.loads((RUN / 'scope-evidence.json').read_bytes())
bodies = {b['va']: b for b in d['bodies']}
ins = bodies['0059ae00']['instructions']
text = {i['va']: i['asm'] for i in ins}
order_va = [i['va'] for i in ins]
assert order_va == sorted(order_va)

PROLOGUE = [
    'mov eax, dword ptr [esp + 8]', 'sub esp, 0x30', 'lea ecx, [esp]',
    'push esi', 'mov esi, dword ptr [esp + 0x38]', 'push edi', 'push ecx',
    'lea edx, [esi + 0x110]', 'lea edi, [esi + eax*4 + 0x680]', 'push edx',
    'call 0x59b580', 'mov eax, dword ptr [esp + 0x4c]', 'add esp, 8',
    'test eax, eax', 'jle 0x59b574',
]
assert [text[va] for va in order_va[:15]] == PROLOGUE

START, STOP = 0x59ae34, 0x59b56e
body = [(va, text[va]) for va in order_va if START <= int(va, 16) <= STOP]
assert body[0][1] == 'fld dword ptr [esp + 0x28]', body[0]
assert body[-1][1] == 'jne 0x59ae34', body[-1]

shift = 0          # bytes added to edi by the hoisted loop advance
pairs = []         # (window index, matrix slot index) in original order
outputs = []
pos = 0
while pos < len(body):
    va, a = body[pos]
    if a == 'add edi, 0x30':
        assert body[pos + 1][1] == 'dec eax', body[pos + 1]
        assert shift == 0, 'single loop advance'
        shift = 0x30
        pos += 2
        continue
    if a == 'jne 0x59ae34':
        pos += 1
        continue
    load = re.fullmatch(r'fld dword ptr \[esp \+ (0x[0-9a-f]+|\d+)\]', a)
    if load:
        w = (int(load.group(1), 0) - 8) // 4
        m = re.fullmatch(r'fmul dword ptr \[esi \+ (0x[0-9a-f]+|\d+)\]', body[pos + 1][1])
        assert m, body[pos + 1]
        slot = (int(m.group(1), 0) - 0x140) // 4
        assert 0 <= w <= 11 and 0 <= slot <= 11, (w, slot)
        pairs.append((w, slot))
        pos += 2
        continue
    if a == 'faddp st(1)':
        pos += 1
        continue
    add = re.fullmatch(r'fadd dword ptr \[edi(?: ([+-]) (0x[0-9a-f]+|\d+))?\]', a)
    if add:
        assert len(pairs) == 12, (len(pairs), a)
        off = 0 if add.group(1) is None else int(add.group(2), 0) * (1 if add.group(1) == '+' else -1)
        out_index = (off + shift) // 4
        store = body[pos + 1][1]
        slot = int(re.search(r'\[esi \+ (0x[0-9a-f]+)\]', store).group(1), 16)
        assert store.startswith('fst dword ptr') and slot == 0x16c - 4 * out_index, (store, out_index)
        tail = body[pos + 2][1]
        tail_match = re.fullmatch(r'fstp dword ptr \[edi(?: ([+-]) (0x[0-9a-f]+|\d+))?\]', tail)
        assert tail_match, tail
        tail_off = 0 if tail_match.group(1) is None else \
            int(tail_match.group(2), 0) * (1 if tail_match.group(1) == '+' else -1)
        assert tail_off == off, (tail, off)
        outputs.append(dict(order=list(pairs), slot=(slot - 0x140) // 4, out=out_index))
        pairs = []
        pos += 3
        continue
    raise AssertionError(f'unexpected {va} {a}')

assert len(outputs) == 12, len(outputs)
for k, o in enumerate(outputs):
    assert o['out'] == k, o
    assert o['slot'] == 11 - k, o
    order = [s for _, s in o['order']]
    assert sorted(order) == list(range(12)), (k, order)
    assert all((slot + k) % 12 == w for w, slot in o['order']), (k, o['order'])

lines = []
for o in outputs:
    terms = ' + '.join(f'prod(w[{w}],m[{slot}])' for w, slot in o['order'])
    lines.append('    {')
    lines.append(f'    double s = {terms} + out[{o["out"]}];')
    lines.append(f'    const float r = static_cast<float>(s);')
    lines.append(f'    m[{o["slot"]}] = r; out[{o["out"]}] = r;')
    lines.append('    }')
result = (
    '// Generated by extract.py from original 0059ae00; do not edit by hand.\n'
    '// One fully unrolled original loop iteration: 12 outputs, exact x87 order.\n'
    'static void audio_coded_matrix_block_0059ae00(float* w,float* m,float* out) {\n'
    + '\n'.join(lines) + '\n}\n')
(RUN / 'audio_coded_matrix_552.inc').write_text(result, encoding='utf-8', newline='\n')
print('orders', [[s for _, s in o['order']] for o in outputs])
print('slots', [o['slot'] for o in outputs])
print('wrote', len(result), 'bytes')
