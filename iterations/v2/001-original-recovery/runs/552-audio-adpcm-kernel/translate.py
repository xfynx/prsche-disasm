"""Emit static MSVC x86 assembly from the complete pinned six-body instruction census.

This is source translation, not a runtime original-code loader. Every original
instruction is checked against the immutable PE before emitting source. Only
code/data relocations and the local switch transport differ.
"""
import hashlib
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
RUN = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('n552translate', ROOT / 'scripts/research/verify-v2-native-batch.py')
n = importlib.util.module_from_spec(spec)
spec.loader.exec_module(n)
raw = (ROOT / 'local/game/Porsche.exe').read_bytes()
d = json.loads((RUN / 'scope-evidence.json').read_bytes())
assert hashlib.sha256(raw).hexdigest() == d['original_sha256']
names = {
    0x59a910: ('audio_coded_decode_0059a910', 'U,U'),
    0x59abe0: ('audio_coded_dequantize_0059abe0', 'U,U,U,I'),
    0x59ad80: ('audio_coded_skip_bits_0059ad80', 'U,U'),
    0x59adc0: ('audio_coded_smooth_0059adc0', 'U'),
    0x59ae00: ('audio_coded_synthesize_0059ae00', 'U,U,I'),
    0x59b580: ('audio_coded_window_0059b580', 'U,U'),
    0x59a8c0: ('audio_adpcm_read_bits_0059a8c0', ''),
    0x598a50: ('audio_stream_copy_forward_00598a50', ''),
}
data = {
    0x5e34c4: 'audio_coded_scale_005e34c4',
    0x5e3504: 'audio_coded_scale_005e34c4+0x40',
    0x5e35c4: 'audio_coded_context_005e35c4',
    0x5e37c8: 'audio_coded_level_005e37c8',
    0x5e37cc: 'audio_coded_level_005e37c8+4',
    0x5e37d0: 'audio_coded_level_005e37c8+8',
    0x5b2468: 'audio_coded_quarter_005b2468',
    0x5b2778: 'audio_coded_gain_005b2778',
    0x5c1808: 'audio_coded_window_005c1808',
    0x5c180c: 'audio_coded_window_005c1808+4',
    0x5c1810: 'audio_coded_window_005c1808+8',
    0x5c1814: 'audio_coded_window_005c1808+0xc',
}
lines = [
    '// Generated by translate.py; original Porsche.exe SHA256 '+d['original_sha256'],
    '// Static source instructions preserve x87 order, register precision, spills,',
    '// PC/RC and stack/status behavior. No global control-word assumption.',
    '#if !defined(_MSC_VER) || !defined(_M_IX86)',
    '#error Exact original x87 instructions require MSVC x86', '#endif',
    '#include "audio_coded_kernel_552.hpp"',
    '#include "../504-audio-coded-constructors/audio_coded_constructors_504.hpp"',
    '#include "../519-audio-stream-capture-fill/audio_stream_capture_fill_519.hpp"',
    'namespace porsche {', '#include "audio_coded_tables_552.inc"',
    'using U=std::uint32_t;using I=std::int32_t;',
]
report = {'original_sha256': d['original_sha256'], 'bodies': [], 'data_bindings': data}
for b in d['bodies']:
    va = int(b['va'], 16)
    buf = n.pe_at(raw, va, b['bytes'])
    assert hashlib.sha256(buf).hexdigest() == b['sha256']
    assert b''.join(bytes.fromhex(i['raw']) for i in b['instructions']) == buf
    targets = {int(i['asm'].split()[1], 16) for i in b['instructions']
               if i['asm'].startswith(('ja ', 'je ', 'jge ', 'jl ', 'jle ', 'jmp 0x', 'jne '))}
    assert targets <= {int(i['va'], 16) for i in b['instructions']}
    name, args = names[va]
    lines += ['', '// '+b['va']+' / '+str(b['bytes'])+' bytes / SHA256 '+b['sha256'],
              '__declspec(naked) void __cdecl '+name+'('+args+') {', '    __asm {']
    records = []
    for i in b['instructions']:
        address = int(i['va'], 16)
        original = i['asm']
        emitted = original
        if address in targets or address in (0x59ad35, 0x59ad3f, 0x59ad47):
            lines.append('    L'+i['va']+':')
        if original.startswith('call '):
            emitted = 'call '+names[int(original.split()[1], 16)][0]
        elif re.match(r'j\w+ 0x', original):
            mnemonic, target = original.split()
            emitted = mnemonic+' L'+f'{int(target,16):08x}'
        elif address == 0x59ad2e:
            assert original == 'jmp dword ptr [eax*4 + 0x59ad70]'
            # Original table: [zero, minus, zero, plus]. Preserve incoming flags
            # even though this cdecl void body's outgoing EFLAGS are not an ABI.
            emitted = '\n        '.join([
                'pushfd', 'test eax,1', 'jz switch_even_552',
                'cmp eax,1', 'je switch_minus_552', 'popfd', 'jmp L0059ad47',
                'switch_even_552:', 'popfd', 'jmp L0059ad35',
                'switch_minus_552:', 'popfd', 'jmp L0059ad3f'])
        else:
            for value, symbol in data.items():
                emitted = re.sub(r'\b'+hex(value)+r'\b', symbol, emitted)
            for operand in re.findall(r'0x[0-9a-f]+', emitted):
                assert not 0x400000 <= int(operand,16) < 0x800000, (i, emitted)
        # Capstone omits the implicit ST0 source; MSVC's assembler requires it.
        if emitted in ('faddp st(1)', 'fsubp st(1)'):
            emitted += ',st(0)'
        lines.append('        '+emitted+' // '+i['va'])
        records.append({'va': i['va'], 'raw': i['raw'], 'source': emitted})
    lines += ['    }', '}']
    report['bodies'].append({'va': b['va'], 'bytes': b['bytes'], 'sha256': b['sha256'], 'instructions': records})
lines += ['}', '']
(RUN / 'audio_coded_kernel_552.cpp').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
(RUN / 'translation-evidence.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8', newline='\n')
print('static source bodies', len(report['bodies']), 'original bytes', sum(b['bytes'] for b in d['bodies']))
