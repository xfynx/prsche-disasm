"""Emit the 0059a910-family read-only data from the pinned original PE bytes.

Every initializer is the original raw bit pattern; no decimal float literal is
used, so the compiled tables cannot drift from the original module.
"""
import importlib.util
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
RUN = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('n552tables', ROOT / 'scripts/research/verify-v2-native-batch.py')
n = importlib.util.module_from_spec(spec)
spec.loader.exec_module(n)
raw = (ROOT / 'local/game/Porsche.exe').read_bytes()
assert n.digest_bytes(raw) == 'ddd748fdbe6d2030e31f9257a4e01852749460b6b58560a6b4a8559d3799ff39'


def words(va, count):
    return list(struct.unpack('<%dI' % count, n.pe_at(raw, va, count * 4)))


def line(name, values, fmt):
    return f'extern const {name}={{' + ','.join(fmt % v for v in values) + '};\n'


scale = words(0x5e34c4, 64)
levels = words(0x5e37c8, 87)
context = list(n.pe_at(raw, 0x5e35c4, 512))
assert max(context) < 29, max(context)
quarter = words(0x5b2468, 1)
gain = words(0x5b2778, 2)
window = words(0x5c1808, 4)
text = (
    '// Generated by gen_tables.py from Porsche.exe ddd748fdbe6d2030e31f9257a4e01852749460b6b58560a6b4a8559d3799ff39\n'
    + line('std::uint32_t audio_coded_scale_005e34c4[64]', scale, '0x%08x')
    + line('std::uint32_t audio_coded_level_005e37c8[87]', levels, '0x%08x')
    + line('std::uint8_t audio_coded_context_005e35c4[512]', context, '0x%02x')
    + line('std::uint32_t audio_coded_quarter_005b2468', quarter, '0x%08x')
    + line('std::uint32_t audio_coded_gain_005b2778[2]', gain, '0x%08x')
    + line('std::uint32_t audio_coded_window_005c1808[4]', window, '0x%08x'))
(RUN / 'audio_coded_tables_552.inc').write_text(text, encoding='utf-8', newline='\n')
data = {'va': {'005e34c4': 256, '005e37c8': 348, '005e35c4': 512, '005b2468': 4,
               '005b2778': 8, '005c1808': 16}}
report = {'original_sha256': n.digest_bytes(raw),
          'tables': {va: {'bytes': size, 'sha256': n.digest_bytes(n.pe_at(raw, int(va, 16), size))}
                     for va, size in data['va'].items()},
          'level_records': [levels[i:i + 3] for i in range(0, 87, 3)],
          'context_max': max(context)}
(RUN / 'table-evidence.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8', newline='\n')
print('tables', len(text), 'context max', max(context))
